const khuVucDanhSachPhim =
    document.getElementById("danhSachPhim");

const thamSoURL =
    new URLSearchParams(window.location.search);

let maPhimDangUuTien =
    Number(thamSoURL.get("phim"));

if (
    !Number.isInteger(maPhimDangUuTien) ||
    maPhimDangUuTien <= 0
) {
    maPhimDangUuTien = null;
}

function hienThiPhimTheoNgay(ngayDuocChon) {
    const cacPhimTrongNgay =
        duLieuLichChieu[ngayDuocChon] || [];

    if (cacPhimTrongNgay.length === 0) {
        khuVucDanhSachPhim.innerHTML = `
            <div class="khong-co-lich-chieu">
                <h3>Không có lịch chiếu</h3>

                <p>
                    Hiện chưa có phim được xếp lịch
                    vào ngày này.
                </p>
            </div>
        `;

        return;
    }

    let noiDungHTML = "";

    cacPhimTrongNgay.forEach(function (phim, chiSoPhim) {
        let noiDungDinhDang = "";

        phim.cacDinhDang.forEach(function (dinhDang) {
            const cacPhong = dinhDang.cacSuatChieu
                .map(function (suatChieu) {
                    return `
                        <th>
                            ${suatChieu.phong}
                        </th>
                    `;
                })
                .join("");

            const cacKhungGio = dinhDang.cacSuatChieu
                .map(function (suatChieu) {
                    return `
                        <td
                            class="time-cell"
                            data-ma-suat-chieu="${suatChieu.maSuatChieu}"
                            data-ma-phim="${phim.maPhim}"
                            data-ten-phim="${phim.tenPhim}"
                            data-ngay-chieu="${ngayDuocChon}"
                            data-gio-chieu="${suatChieu.gio}"
                            data-phong="${suatChieu.phong}"
                            data-loai-chieu="${dinhDang.loaiChieu}"
                            data-ngon-ngu="${dinhDang.ngonNgu}"
                        >
                            ${suatChieu.gio}
                        </td>
                    `;
                })
                .join("");

            noiDungDinhDang += `
                <div class="format-row">
                    ${dinhDang.loaiChieu}
                    <b>| ${dinhDang.ngonNgu}</b>
                </div>

                <table class="showtimes">
                    <tr>
                        ${cacPhong}
                    </tr>

                    <tr>
                        ${cacKhungGio}
                    </tr>
                </table>
            `;
        });

        let lopMoMacDinh = "";

        // Đi từ Home sang và có mã phim trên URL.
        if (maPhimDangUuTien !== null) {
            if (phim.maPhim === maPhimDangUuTien) {
                lopMoMacDinh = "open";
            }
        } else if (chiSoPhim === 0) {
            // Vào trang lịch chiếu trực tiếp:
            // mở phim đầu tiên.
            lopMoMacDinh = "open";
        }

        noiDungHTML += `
            <div
                class="movie ${lopMoMacDinh}"
                data-ma-phim="${phim.maPhim}"
            >
                <div class="movie-head">
                    <span class="badge ${phim.lopDoTuoi}">
                        ${phim.doTuoi}
                    </span>

                    <span class="movie-title">
                        ${phim.tenPhim}
                    </span>

                    <span class="chev">›</span>
                </div>

                <div class="movie-body">
                    ${noiDungDinhDang}
                </div>
            </div>
        `;
    });

    khuVucDanhSachPhim.innerHTML = noiDungHTML;
}



