khuVucDanhSachPhim.addEventListener(
  "click",
  function (suKien) {
    const tieuDePhim =
      suKien.target.closest(".movie-head");

    if (!tieuDePhim) {
      return;
    }

    const khungPhimDuocBam =
      tieuDePhim.closest(".movie");

    const phimDangMo =
      khungPhimDuocBam.classList.contains("open");

    // Đóng tất cả khung phim.
    const cacKhungPhim =
      khuVucDanhSachPhim.querySelectorAll(".movie");

    cacKhungPhim.forEach(function (khungPhim) {
      khungPhim.classList.remove("open");
    });

    // Nếu phim vừa bấm đang đóng thì mở phim đó.
    if (!phimDangMo) {
      khungPhimDuocBam.classList.add("open");

      maPhimDangUuTien =
        Number(khungPhimDuocBam.dataset.maPhim);
    } else {
      maPhimDangUuTien = null;
    }
  }
);


// Đọc mã phim được gửi từ trang Home.
// Ví dụ: lich-chieu.html?phim=2


// Không có mã phim hoặc mã không hợp lệ.
if (
  !Number.isInteger(maPhimDangUuTien) ||
  maPhimDangUuTien <= 0
) {
  maPhimDangUuTien = null;
}


